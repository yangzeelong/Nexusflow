namespace nexusflow {

// --- PipelineBuilder's Private Implementation (m_pImpl) ---
// This class is now extremely simple. It's just a data-holding struct
// to store the user's configuration before the Graph is built.
class PipelineBuilder::Impl {
public:
    std::vector<std::shared_ptr<Module>> modules;
    std::vector<std::pair<std::string, std::string>> connections;
    /// Per-module config for instances added through AddModule(), which have no
    /// config of their own. YAML nodes carry it on the node; this is the same
    /// thing for the programmatic path.
    std::unordered_map<std::string, Config> moduleConfigs;
};

// --- PipelineBuilder's Public Methods ---

PipelineBuilder::PipelineBuilder() : m_pImpl(std::make_unique<Impl>()) {}

PipelineBuilder::~PipelineBuilder() = default;

// --- Move Semantics ---
// The default move operations generated by the compiler are sufficient here.
PipelineBuilder::PipelineBuilder(PipelineBuilder&&) noexcept = default;
PipelineBuilder& PipelineBuilder::operator=(PipelineBuilder&&) noexcept = default;

PipelineBuilder& PipelineBuilder::AddModule(const std::shared_ptr<Module>& module) {
    if (m_pImpl && module) {
        m_pImpl->modules.push_back(std::move(module));
    }
    return *this;
}

PipelineBuilder& PipelineBuilder::Connect(const std::string& srcModuleName, const std::string& dstModuleName) {
    if (m_pImpl && !srcModuleName.empty() && !dstModuleName.empty()) {
        m_pImpl->connections.emplace_back(srcModuleName, dstModuleName);
    }
    return *this;
}

PipelineBuilder& PipelineBuilder::SetModuleConfig(const std::string& moduleName, const Config& config) {
    if (m_pImpl && !moduleName.empty()) {
        m_pImpl->moduleConfigs[moduleName] = config;
    }
    return *this;
}

std::unique_ptr<Pipeline> PipelineBuilder::Build() {
    LOG_ERROR("PipelineBuilder::Build() needs the edge queue capacity: call Build(capacity).");
    return nullptr;
}

std::unique_ptr<Pipeline> PipelineBuilder::Build(int edgeQueueCapacity) {
    if (!m_pImpl) {
        return nullptr; // Builder has been consumed
    }

    if (edgeQueueCapacity <= 0) {
        LOG_ERROR("PipelineBuilder::Build({}) needs a positive edge queue capacity; refusing to build a pipeline "
                  "without one.",
                  edgeQueueCapacity);
        return nullptr;
    }

    if (m_pImpl->modules.empty()) {
        LOG_ERROR("PipelineBuilder::Build() called without any module.");
        return nullptr;
    }

    // --- Step 1: Create a Graph object ---
    auto graph = std::make_unique<Graph>();
    graph->setName("Programmatically_Built_Pipeline"); // Or generate a unique name

    // --- Step 2: Create all Node objects and populate a lookup map ---
    // This map allows us to quickly find a Node shared_ptr by its name.
    std::unordered_map<std::string, std::shared_ptr<Node>> nodeLookupMap;

    for (const auto& module_ptr : m_pImpl->modules) {
        if (!module_ptr) continue;

        const std::string& moduleName = module_ptr->GetModuleName();

        // Assign the pre-created module instance
        auto node = std::make_shared<NodeWithModulePtr>(moduleName, module_ptr);
        // Carry any config the builder was given for this module, the same way a
        // yaml node carries its own.
        const auto configIt = m_pImpl->moduleConfigs.find(moduleName);
        if (configIt != m_pImpl->moduleConfigs.end()) {
            node->config = configIt->second;
        }

        nodeLookupMap[moduleName] = node;
    }

    // --- Step 3: Add edges to the graph based on connections ---
    if (m_pImpl->connections.empty() && m_pImpl->modules.size() > 1) {
        LOG_ERROR("PipelineBuilder has {} modules but no connections; refusing to build a disconnected pipeline.",
                  m_pImpl->modules.size());
        return nullptr;
    }

    for (const auto& conn : m_pImpl->connections) {
        const std::string& fromName = conn.first;
        const std::string& toName = conn.second;

        auto fromIt = nodeLookupMap.find(fromName);
        auto toIt = nodeLookupMap.find(toName);

        if (fromIt == nodeLookupMap.end() || toIt == nodeLookupMap.end()) {
            LOG_ERROR("Connection '{} -> {}' references a module that was not added to the builder.", fromName, toName);
            return nullptr;
        }

        graph->addEdge(fromIt->second, toIt->second);
    }

    // --- Step 4: every module needs at least one edge ---
    // Actors are derived from the edge list, so a module with no edge never gets a
    // worker. The pipeline used to build successfully and then quietly run
    // without that module (a single-module pipeline ran nothing at all).
    {
        std::unordered_map<std::string, std::size_t> degree;
        for (const auto& module : m_pImpl->modules) {
            degree[module->GetModuleName()] = 0;
        }
        for (const auto& conn : m_pImpl->connections) {
            ++degree[conn.first];
            ++degree[conn.second];
        }
        for (const auto& entry : degree) {
            if (entry.second == 0) {
                LOG_ERROR("Module '{}' is connected to nothing; every module in a pipeline needs at least one edge.",
                          entry.first);
                return nullptr;
            }
        }
    }

    // --- Step 5: Check for cycles ---
    if (graph->hasCycle()) {
        LOG_ERROR("The graph built from the builder contains a cycle; refusing to build the pipeline.");
        return nullptr;
    }

    // --- Step 6: Create the Pipeline from the fully constructed Graph ---
    auto pipeline = std::unique_ptr<Pipeline>(new Pipeline());
    pipeline->m_pImpl->messageQueueCapacity = edgeQueueCapacity;
    const ErrorCode code = pipeline->InitWithGraph(std::move(graph));

    m_pImpl.reset(); // Consume the builder

    if (code != ErrorCode::SUCCESS) {
        LOG_ERROR("Failed to initialize the pipeline built from the builder's modules.");
        return nullptr;
    }
    return pipeline;
}

} // namespace nexusflow